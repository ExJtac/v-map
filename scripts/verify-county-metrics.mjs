import assert from 'node:assert/strict';
import { contestMetrics, compareContest, relativeChange, previousElectionYear, expectedPriorYear, populationAt, populationChange, regularNovemberBallot, ballotComparison, ballotsPerResident, votingMethodShares } from '../src/county-metrics.js';
const row = { stateFips:'01', stage:'general', special:false, totalVotes:150, candidates:[{party:'Republican',votes:90},{party:'Democrat',votes:50},{party:'Other',votes:10}] };
assert.deepEqual(contestMetrics(row), {total:150,republican:90,democrat:50});
assert.equal(relativeChange(10, 0), null);
assert.equal(previousElectionYear([2016,2020,2024],2024),2020);
assert.equal(compareContest(row,[{...row,totalVotes:100}], 'president').total,50);
assert.ok(compareContest(row,[row],'house').reason);
assert.ok(compareContest(row,[row],'senate').reason);
assert.equal(compareContest({...row,provisional:true},[row],'president').provisional, true);
assert.equal(contestMetrics({...row,sourceNeedsReview:true}),null);
assert.equal(contestMetrics({...row,candidates:[{party:'Other',votes:150}]}).republican,null);
assert.deepEqual(contestMetrics({...row,totalVotes:0,candidates:[{name:'R',party:'Republican',votes:0},{name:'D',party:'Democrat',votes:0}]}),{total:0,republican:0,democrat:0});
const withUnknown = {...row,totalVotes:170,reportingCategories:[{name:'write-ins',category:'sourceWriteInEntries',votes:5},{name:'sv',category:'sourceReportingCategory',votes:15}]};
assert.equal(contestMetrics(withUnknown).total,155);
assert.equal(contestMetrics(withUnknown).sourceReportedTotal,170);
assert.ok(compareContest(withUnknown,[row],'president').reason);

assert.equal(expectedPriorYear({stateFips:'08'}, 'governor', 2022), 2018);
assert.equal(expectedPriorYear({stateFips:'33'}, 'governor', 2022), 2020);
assert.equal(expectedPriorYear({stateFips:'08', special:true}, 'governor', 2022), null);
assert.equal(populationAt([{year:2025,value:5},{year:2023,value:3}],2024).year,2023);
assert.equal(populationAt([{year:2025,value:5}],2024),null);
assert.equal(relativeChange(50, 100), -50);
assert.equal(relativeChange(5, -1), null);
assert.equal(contestMetrics({...row, candidates:[{name:'A',party:'Republican',votes:null},{name:'B',party:'Democrat',votes:3}]}).republican, null);
assert.equal(contestMetrics({...row, candidates:[{name:'A',party:'Republican',votes:90},{name:'B',party:'Democrat',votes:50},{name:'OTHER',party:'Republican',votes:10}]}).republican, 90);
assert.equal(contestMetrics({...row, voteTotalMismatch:true}), null);
assert.ok(compareContest(row,[{...row,sourceTotalConflict:true}], 'president').reason);
assert.equal(expectedPriorYear({...row,contestType:'recall-question'}, 'governor', 2022), null);
assert.equal(expectedPriorYear({...row,stage:'gen runoff'}, 'governor', 2022), null);
assert.equal(populationChange({year:2020,value:110,sourceId:'b'},{year:2019,value:100,sourceId:'a'}), null);
assert.equal(populationChange({year:2021,value:110,sourceId:'b'},{year:2020,value:100,sourceId:'b'}), 10);
assert.equal(populationChange({year:2021,value:110,sourceId:'b'},{year:2019,value:100,sourceId:'b'}), null);

const turnout2022 = {year:2022,electionDate:'2022-11-08',stage:'general',special:false,ballotsCast:100,provisional:false,unofficial:false};
const turnout2026 = {year:2026,electionDate:'2026-11-03',stage:'general',special:false,ballotsCast:90,provisional:true};
const presidential2024 = {year:2024,electionDate:'2024-11-05',stage:'general',special:false,ballotsCast:200};
assert.equal(ballotComparison([turnout2022, turnout2026, presidential2024],2026,true).value,-10);
assert.equal(ballotComparison([turnout2022, turnout2026, presidential2024],2026,true).priorYear,2022);
assert.equal(ballotComparison([turnout2022, turnout2026],2026,true).provisional,true);
assert.equal(ballotComparison([turnout2026, presidential2024],2026,true).value,undefined);
assert.equal(ballotComparison([turnout2022, turnout2026],2026,false).value,undefined);
assert.equal(ballotComparison([{...turnout2022,ballotsCast:0}, turnout2026],2026,true).value,undefined);
assert.equal(ballotComparison([turnout2022,{...turnout2026,ballotsCast:0}],2026,true).value,-100);
assert.equal(ballotComparison([{...turnout2022,provisional:undefined,unofficial:undefined},turnout2026],2026,true).value,undefined);
assert.equal(ballotComparison([{...turnout2022,unofficial:true}, turnout2026],2026,true).value,undefined);
assert.equal(ballotComparison([{...turnout2022,boundaryNote:'Changed county'}, turnout2026],2026,true).value,undefined);
assert.equal(regularNovemberBallot([{...turnout2022,stage:'primary'}],2022),null);
assert.equal(regularNovemberBallot([{...turnout2022,special:true}],2022),null);
assert.equal(regularNovemberBallot([turnout2022,turnout2022],2022),null);
assert.equal(ballotsPerResident(250, 1000),25);
assert.equal(ballotsPerResident(0, 1000),0);
assert.equal(ballotsPerResident(10, 0),null);
assert.equal(ballotsPerResident(null, 1000),null);
assert.equal(ballotsPerResident(10, null),null);
const govComparison = compareContest({...row, provisional:true, totalVotes:120}, [{...row,totalVotes:100}], 'governor');
assert.equal(govComparison.total,20);
assert.equal(govComparison.provisional,true);
assert.ok(compareContest({...row,provisional:true,sourceNeedsReview:true}, [row], 'governor').reason);
assert.ok(compareContest(row, [{...row,provisional:true}], 'governor').reason);
assert.equal(ballotComparison([turnout2022,{...turnout2026,provisional:false}],2026,true).provisional,false);
assert.deepEqual(votingMethodShares({ballotsCast:100, voteByMailVoters:80, precinctVoters:20}), {mail:80, precinct:20});
assert.deepEqual(votingMethodShares({ballotsCast:100, voteByMailVoters:100, precinctVoters:0}), {mail:100, precinct:0});
assert.equal(votingMethodShares({ballotsCast:100}), null);
assert.equal(votingMethodShares({ballotsCast:100, voteByMailVoters:80, precinctVoters:10}), null);
assert.equal(votingMethodShares({ballotsCast:0, voteByMailVoters:0, precinctVoters:0}), null);
assert.equal(votingMethodShares({ballotsCast:100, voteByMailVoters:null, precinctVoters:100}), null);
